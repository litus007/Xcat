export class Translations {
    static get<T = string>(key: keyof typeof Texts, values?: any): T {
        const text = Texts[key];
        if (text === undefined) {
            BxLogger.warning('Translations', `Clau de traducció inexistent: ${key}`);
            return key as unknown as T;
        }

        if (typeof text === 'function') {
            return (text as (v: any) => string)(values) as unknown as T;
        }

        return text as unknown as T;
    }
}

export const t = Translations.get;
export const ut = (text: string): string => {
    BxLogger.warning('Text sense traduir', text);
    return text;
};
